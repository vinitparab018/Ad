-- PostgreSQL reference schema for a planned production migration.
-- The current runtime uses SQLite; this file is not automatically applied.
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role VARCHAR(16) NOT NULL DEFAULT 'editor' CHECK(role IN ('admin','editor')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS articles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(240) NOT NULL, slug VARCHAR(120) NOT NULL UNIQUE,
 summary VARCHAR(500) NOT NULL, body TEXT NOT NULL DEFAULT '',
 category VARCHAR(80) NOT NULL DEFAULT 'India', author VARCHAR(120) NOT NULL DEFAULT 'NewsOrbit Desk',
 source_name VARCHAR(160) NOT NULL DEFAULT 'NewsOrbit', source_url TEXT, image_url TEXT, image_credit VARCHAR(240),
 tags TEXT NOT NULL DEFAULT '', seo_title VARCHAR(240), meta_description VARCHAR(300), canonical_url TEXT,
 featured BOOLEAN NOT NULL DEFAULT false, published_at TIMESTAMPTZ, scheduled_at TIMESTAMPTZ,
 status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','scheduled','published','unpublished')),
 is_demo BOOLEAN NOT NULL DEFAULT false, created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_articles_source_url ON articles(source_url) WHERE source_url IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_articles_public ON articles(status,published_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_schedule ON articles(status,scheduled_at);
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE,
 consent_text TEXT NOT NULL, consented_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','subscribed','unsubscribed')),
 provider_id TEXT, unsubscribe_token TEXT NOT NULL UNIQUE, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT, action VARCHAR(80) NOT NULL,
 article_id BIGINT, ip_hash CHAR(64), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
